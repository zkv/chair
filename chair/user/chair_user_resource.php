class Chair_User_Resource
{
	private $resource, $user, $context;
	public function __construct($resource, $user)
	{
		$this->resource = $resource;
		$this->user = $user;
		$this->context = Chair_Context_Manager::getContext(__CLASS__); 
	}
	public function __call($name, $args)
	{
		if (!count(array_intersect($this->user->getGroups(), $this->context->getACL()->getGroupsByTargetAndAction($this->resource, $name)))) {
			throw new Chair_User_Resource_Exception();
		}
		return call_user_func_array(array($this->context->getResource($this->resource), $name), $args);
	}
}
